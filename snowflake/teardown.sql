/*
  Removes everything bootstrap.sql created. Run as ACCOUNTADMIN.
  Destructive: drops all loaded data and models. Useful before moving to a new trial account.
*/

USE ROLE ACCOUNTADMIN;

DROP USER IF EXISTS DLT_SVC;
DROP USER IF EXISTS DBT_PROD_SVC;
DROP USER IF EXISTS DBT_CI_SVC;

DROP DATABASE IF EXISTS ANALYTICS_DEV;
DROP DATABASE IF EXISTS ANALYTICS;
DROP DATABASE IF EXISTS RAW;

DROP WAREHOUSE IF EXISTS LOADING_WH;
DROP WAREHOUSE IF EXISTS TRANSFORMING_WH;
DROP WAREHOUSE IF EXISTS REPORTING_WH;

DROP RESOURCE MONITOR IF EXISTS SAAS_BILLING_MONITOR;

DROP ROLE IF EXISTS REPORTER;
DROP ROLE IF EXISTS DEVELOPER;
DROP ROLE IF EXISTS TRANSFORMER;
DROP ROLE IF EXISTS LOADER;
